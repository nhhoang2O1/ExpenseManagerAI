    public IReadOnlyList<CategoryPatternRule> PatternRules { get; }
    public IReadOnlyList<CategoryCompositionRule> CompositionRules { get; }
    public IReadOnlyList<MerchantBrandProfile> BrandProfiles { get; }

    public CategoryRuleSet(
        IReadOnlyList<CategoryPatternRule>? patternRules = null,
        IReadOnlyList<CategoryCompositionRule>? compositionRules = null,
        IReadOnlyList<MerchantBrandProfile>? brandProfiles = null)
    {
        PatternRules = patternRules ?? DefaultPatternRules();
        CompositionRules = compositionRules ?? DefaultCompositionRules();
        BrandProfiles = (brandProfiles ?? []).Select(profile => profile with
        {
            Contribution = Math.Clamp(profile.Contribution, 0m, 4m)
        }).ToList();
    }

