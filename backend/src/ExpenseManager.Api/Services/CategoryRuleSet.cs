    private static CategoryPatternRule Rule(
        string id,
        SemanticExpenseCategory category,
        CategoryRuleKind kind,
        CategoryEvidenceSource source,
        CategoryRuleScope scope,
        decimal weight,
        IReadOnlyList<string> patterns,
        IReadOnlyList<string> tags,
        string reason,
        bool fuzzy = false) =>
        new(id, category, kind, source, scope, weight, patterns, tags, reason, fuzzy);

    private static CategoryPatternRule Tag(
        string id,
        CategoryRuleKind kind,
        CategoryRuleScope scope,
        IReadOnlyList<string> patterns,
        IReadOnlyList<string> tags,
        string reason) =>
        new(id, null, kind, CategoryEvidenceSource.CONTENT, scope, 0m, patterns, tags, reason);

    private static CategoryCompositionRule Compose(
        string id,
        SemanticExpenseCategory category,
        decimal weight,
        IReadOnlyList<string> all,
        IReadOnlyList<string> any,
        IReadOnlyList<string> forbidden,
        string reason,
        IReadOnlyDictionary<SemanticExpenseCategory, decimal>? penalties = null) =>
        new(id, category, weight, all, any, forbidden, reason, penalties);
